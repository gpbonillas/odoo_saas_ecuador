# -*- coding: utf-8 -*-
from odoo import models, fields, api
import logging

_logger = logging.getLogger(__name__)


class AccountMove(models.Model):
    _inherit = "account.move"

    # NOTE: l10n_ec_sustento_code (Selection) is defined by l10n_ec_edi
    # (a dependency of this module). It must NOT be redefined here as a
    # plain Char or it would override the Selection and break SRI views.

    l10n_ec_withholding_id = fields.Many2one(
        "account.retention",
        string="Withholding",
        copy=False,
        readonly=True,
        help="Comprobante de Retención automatically generated when this "
             "vendor bill was posted.",
    )
    l10n_ec_auto_withholding = fields.Boolean(
        string="Auto Withholding",
        default=True,
        help="Calculate the IR/IVA withholding automatically on posting "
             "(requires a withholding agent: company or partner flagged).",
    )

    # =========================================================================
    # AUTO-DETECTION OF WITHHOLDINGS ON CONFIRMATION
    # Given a vendor bill of a withholding agent, the IR/IVA retention is
    # computed from:
    #   * the product's explicit IR/IVA withholding codes (if set), else
    #   * the SRI tariff table (l10n_ec.retention.tariff) keyed by the
    #     RUC 4th digit / activity of the vendor.
    # =========================================================================

    def _l10n_ec_should_auto_withhold(self):
        self.ensure_one()
        if self.move_type != "in_invoice":
            return False
        if not self.l10n_ec_auto_withholding:
            return False
        company = self.company_id
        if company.account_fiscal_country_id.code != "EC" and (
            not company.country_id or company.country_id.code != "EC"
        ):
            return False
        ICP = self.env["ir.config_parameter"].sudo()
        if ICP.get_param("l10n_ec.withholding_auto_detect", "True").lower() not in (
            "true",
            "1",
            "yes",
        ):
            return False
        if not (
            company.l10n_ec_withhold_agent
            or (self.partner_id and self.partner_id.l10n_ec_withhold_agent)
        ):
            return False
        if not self.invoice_date:
            return False
        # Do not duplicate an existing (active) withholding for this bill
        existing = self.env["account.retention"].search(
            [
                ("invoice_id", "=", self.id),
                ("state", "!=", "cancel"),
            ],
            limit=1,
        )
        if existing:
            return False
        return True

    @api.model
    def _l10n_ec_line_iva_amount(self, line):
        """VAT amount generated by an invoice line (positive taxes only)."""
        vat = 0.0
        for tax in line.tax_ids:
            if tax.amount_type == "percent" and tax.amount > 0:
                vat += line.price_subtotal * tax.amount / 100.0
        return vat

    @api.model
    def _l10n_ec_resolve_withholding_code(self, product, tax_type, activity, partner):
        """Product-explicit code wins, otherwise the tariff table is used."""
        if product:
            if tax_type == "renta" and product.l10n_ec_ir_retention_tax_id:
                return product.l10n_ec_ir_retention_tax_id
            if tax_type == "iva" and product.l10n_ec_iva_retention_tax_id:
                return product.l10n_ec_iva_retention_tax_id
        return self.env["l10n_ec.retention.tariff"].resolve(
            tax_type, activity, partner
        )

    def _l10n_ec_calculate_withholding_vals(self):
        """
        Returns account.retention.line values for this vendor bill.
        IR base = untaxed line amount; IVA base = VAT of the line.
        """
        self.ensure_one()
        partner = self.partner_id
        tariff = self.env["l10n_ec.retention.tariff"]
        vals = []
        for line in self.invoice_line_ids:
            if line.display_type not in (False, "product"):
                continue
            if not line.price_subtotal:
                continue
            product = line.product_id
            activity = (
                product.l10n_ec_withholding_activity
                if product
                else "goods"
            )

            ir_tax = self._l10n_ec_resolve_withholding_code(
                product, "renta", activity, partner
            )
            if ir_tax:
                vals.append(
                    {
                        "tax_type": "1",
                        "tax_id": ir_tax.id,
                        "base": line.price_subtotal,
                        "invoice_id": self.id,
                    }
                )

            iva_base = self._l10n_ec_line_iva_amount(line)
            if iva_base:
                iva_tax = self._l10n_ec_resolve_withholding_code(
                    product, "iva", activity, partner
                )
                if iva_tax:
                    vals.append(
                        {
                            "tax_type": "2",
                            "tax_id": iva_tax.id,
                            "base": iva_base,
                            "invoice_id": self.id,
                        }
                    )
        return vals

    def _l10n_ec_create_auto_withholding(self):
        """Creates the draft comprobante de retención for a posted bill."""
        self.ensure_one()
        if not self._l10n_ec_should_auto_withhold():
            return False
        line_vals = self._l10n_ec_calculate_withholding_vals()
        if not line_vals:
            return False
        retention = (
            self.env["account.retention"]
            .with_company(self.company_id)
            .create(
                {
                    "invoice_id": self.id,
                    "partner_id": self.partner_id.id,
                    "company_id": self.company_id.id,
                    # Same day as the invoice: always inside the 5-business-day
                    # window (LRTI art. 50; días hábiles: Código Tributario
                    # art. 12) of the confirmation.
                    "date": self.invoice_date,
                    "l10n_ec_sri_status": "draft",
                    "retention_line_ids": [
                        (0, 0, vals) for vals in line_vals
                    ],
                }
            )
        )
        self.l10n_ec_withholding_id = retention.id
        _logger.info(
            "Auto withholding %s generated for vendor bill %s",
            retention.name,
            self.name,
        )
        return retention

    def action_post(self):
        result = super().action_post()
        for move in self:
            try:
                move._l10n_ec_create_auto_withholding()
            except Exception:
                # Never block invoice confirmation because of auto-detection;
                # the retention can always be created manually from the bill.
                _logger.exception(
                    "Auto-withholding failed for vendor bill %s", move.name
                )
        return result
